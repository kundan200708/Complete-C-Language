/*
Decision Control Statement:-
                         ---> Decision control statement are used to control execution flow within the program .
                         ---> It includes branching of statements or codes helps to write condition ,selection,jump
                         and iteration in the C program.
 
 
(*)Control statement consist on the following:-
                                   (1)If statement 
                                   (2)If-Else Statement 
                                   (3)Ladder - If Statement
                                   (4)Nested -If  Statement 
                                   (5) Go- to statement
                                   (6) Looping Statement 

(*)The commonly operators are used in this statements are as below :-
             Operators               Description
           ==              Equal to (e.g : x == y)
           !=              Not equal to (e.g : x != y)
            >              Greater than (e.g : x == y)
            <              Less than (e.g : x == y)
           >=              Greater than equal to (e.g : x == y)
           >=               Less than equal to (e.g : x == y)
           ==              Equal to (e.g : x == y)


*/