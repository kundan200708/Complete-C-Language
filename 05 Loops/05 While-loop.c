/*
While Loop:-
          --> A while loop is used to check undetermine or unknown condition in the program and perform the 
          task rapidly .
          -->It is also called entry controlled loop in which condition is checked before execution of loop
          body.

(*)Syntax for While loop :-
                       Initialization:
                        while(condition)
                        {
                        
                        // statements

                        }
 
It is working like that:

              Initialize
                  ↓
             Check condition
                  ↓
      True ──→ Execute body ──→ Update
       │                         │
       └───────────────←─────────┘
                  ↓
                False
                  ↓
               Exit loop

               
*/