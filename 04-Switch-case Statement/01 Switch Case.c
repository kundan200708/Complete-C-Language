/*
Switch - Case Statement:- 
                        --> It is an alternate of ladder if-else that allows you to perform different tasks
                        on the basis of cases which means switch statements takes an expression and provide 
                        multiple cases that allows to write statement or codes.

(*)Switch Statement  consist on the following :-
           
                      (1) Case:- It is a option of switch statement and allows execution when condition is 
                      matched with with switch expression.

NOTE:- Case can be either int or char type data .

                      (2) Break:- It is used to transfer the control at outside of switch body.


                      (3) Default:- When no any cases is matched with switch expression ,then default statement
                      will automatically execute .

                      
Syntax of Switch Case Statement :-
                                switch (expression)
                                   {
                                case value1:
                                   // statements
                                   break;

                                case value2:
                                    // statements
                                   break;

                                case value3:
                                        // statements
                                    break;

                                    default:
                                       // statements
                                    }
            

*/