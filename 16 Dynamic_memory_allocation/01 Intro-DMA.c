/*
(*) Dynamic Memory Allocation:-
                              -->In C language dynamic memory allocation is refers to allocate memory space at runtime,
                               which allowing the programmer to manage memory dynamically it very useful when you don't know how many memory space are required at compile time 
                               & it is allocate memory on the base of user input or other runtime condition.

                               -->Dynamic memory allocation means allocating memory during program execution (runtime).


(*)Main functions used in Dynamic memory allocation are given below:-


   malloc() → Allocates memory but does not initialize it.
   calloc() → Allocates memory and initializes it to zero.
   realloc() → Changes the size of allocated memory.
   free() → Releases the allocated memory.


(*) The all these functions are found in <stdlib.h> header file.

*/